-- =============================================================================
-- Você Fashion: estrutura inicial do banco (Supabase)
--
-- Espelha os tipos de src/data/catalog.ts. Regras de acesso (RLS):
--   * Visitante (anon) lê só o que a vitrine mostra: categorias e produtos ativos,
--     estoque, dados da loja, formas de entrega ativas e banner.
--   * Cupons e pedidos NÃO são legíveis pelo visitante. O checkout usa duas funções:
--       check_coupon(code, subtotal)  → valida o cupom sem expor a lista
--       place_order(payload)          → cria o pedido recalculando tudo no servidor
--     (preços, frete, cupom, desconto Pix) e baixando o estoque numa transação.
--   * Administradoras (tabela admin_users) leem e alteram tudo.
-- =============================================================================

