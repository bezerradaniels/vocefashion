/** Dígitos verificadores do CPF (mesma regra de src/lib/format.ts). */
create function public.is_valid_cpf(value text)
returns boolean
language plpgsql
immutable
set search_path = ''
as $$
declare
  d text := regexp_replace(coalesce(value, ''), '\D', '', 'g');
  acc integer;
  r integer;
  len integer;
  i integer;
begin
  if length(d) <> 11 or d ~ '^(\d)\1{10}$' then
    return false;
  end if;
  foreach len in array array[9, 10] loop
    acc := 0;
    for i in 1..len loop
      acc := acc + substr(d, i, 1)::integer * (len + 2 - i);
    end loop;
    r := (acc * 10) % 11;
    if r = 10 then r := 0; end if;
    if r <> substr(d, len + 1, 1)::integer then
      return false;
    end if;
  end loop;
  return true;
end;
$$;

/**
 * Regra do cupom (mesma de applyCoupon em src/data/catalog.ts).
 * Devolve {ok: true, code, discount} ou {ok: false, error}.
 */
create function public.evaluate_coupon(p_code text, p_subtotal numeric)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  c public.coupons;
  discount numeric;
begin
  select * into c from public.coupons where code = upper(trim(coalesce(p_code, '')));
  if not found or not c.active then
    return jsonb_build_object('ok', false, 'error', 'Cupom não encontrado');
  end if;
  if c.expires_at is not null and (now() at time zone 'America/Bahia')::date > c.expires_at then
    return jsonb_build_object('ok', false, 'error', 'Este cupom expirou');
  end if;
  if c.usage_limit is not null and c.used >= c.usage_limit then
    return jsonb_build_object('ok', false, 'error', 'Este cupom esgotou');
  end if;
  if p_subtotal < c.min_subtotal then
    return jsonb_build_object(
      'ok', false,
      'error', 'Válido para compras a partir de R$ ' || replace(to_char(c.min_subtotal, 'FM999G990D00'), '.', ',')
    );
  end if;
  discount := case
    when c.type = 'percent' then round(p_subtotal * c.value) / 100
    else least(c.value, p_subtotal)
  end::numeric(10, 2);
  return jsonb_build_object('ok', true, 'code', c.code, 'discount', discount);
end;
$$;

revoke execute on function public.evaluate_coupon(text, numeric) from public, anon, authenticated;

