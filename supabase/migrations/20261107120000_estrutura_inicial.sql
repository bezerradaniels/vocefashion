create table public.categories (
  id text primary key check (id ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name text not null check (length(trim(name)) > 0),
  active boolean not null default true,
  -- Ordem das pílulas na vitrine (menor primeiro).
  position integer not null default 0
);

create table public.products (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  category_id text not null references public.categories (id) on update cascade,
  name text not null check (length(trim(name)) >= 3),
  price numeric(10, 2) not null check (price > 0),
  -- Preço "de" (riscado). Preenchido e maior que price = produto em promoção.
  old_price numeric(10, 2) check (old_price is null or old_price > price),
  description text not null default '',
  description_more text not null default '',
  photo_label text not null default '',
  -- Caminhos em public/ ("/produtos/x/01.webp") ou URLs do Storage. 01 = capa.
  images text[] not null default '{}',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create index products_category_id_idx on public.products (category_id);

-- Estoque por tamanho numa tabela própria: permite travar a linha (FOR UPDATE) na compra.
create table public.product_stock (
  product_id bigint not null references public.products (id) on delete cascade,
  size public.product_size not null,
  qty integer not null default 0 check (qty >= 0),
  primary key (product_id, size)
);

-- Todo produto novo nasce com as 4 linhas de estoque (zeradas).
create function public.create_product_stock()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.product_stock (product_id, size, qty)
  select new.id, s, 0 from unnest(enum_range(null::public.product_size)) as s
  on conflict do nothing;
  return new;
end;
$$;

revoke execute on function public.create_product_stock() from public, anon, authenticated;

create trigger products_create_stock
  after insert on public.products
  for each row execute function public.create_product_stock();

