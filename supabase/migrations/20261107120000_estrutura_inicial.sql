/**
 * Cancelar devolve as peças ao estoque; sair de "cancelado" baixa de novo
 * (e falha se não houver peça, em vez de vender o que não existe).
 */
create function public.orders_status_stock()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  sign integer;
  item record;
begin
  if new.status = old.status then
    return new;
  end if;
  sign := case
    when new.status = 'cancelado' then 1
    when old.status = 'cancelado' then -1
    else 0
  end;
  if sign = 0 then
    return new;
  end if;
  for item in
    select product_id, size, sum(qty)::integer as qty
    from public.order_items
    where order_id = new.id and product_id is not null
    group by product_id, size
    order by product_id, size
  loop
    update public.product_stock s
    set qty = s.qty + sign * item.qty
    where s.product_id = item.product_id and s.size = item.size;
  end loop;
  return new;
exception
  when check_violation then
    raise exception 'Sem estoque para reativar este pedido.' using errcode = 'P0001', hint = 'sem_estoque';
end;
$$;

revoke execute on function public.orders_status_stock() from public, anon, authenticated;

create trigger orders_status_stock
  after update of status on public.orders
  for each row execute function public.orders_status_stock();

